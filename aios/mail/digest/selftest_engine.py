print("== 8. retention gate (F5) with a fake graph ==")


class FakeGraph:
    def __init__(self, items):
        self.items = list(items)   # [{"id": raw-graph-id}]
        self.deleted = []

    def list_folders(self):
        return {"aios-filed": "F1"}

    def list_folder(self, fid, top, skip=None, filter=None, orderby=None):
        return [m for m in self.items]

    def delete(self, mid):
        self.deleted.append(mid)
        self.items[:] = [m for m in self.items if m["id"] != mid]
        return None


raw_ids = [f"raw-{i}" for i in range(4)]
g = FakeGraph([{"id": rid, "receivedDateTime": "2026-10-01T00:00:00Z"}
               for rid in raw_ids])
cfg4 = ECFG.from_dict({"filed_days": 10, "filed_folder": "AIOS-Filed"})
confirmed = {msg_key(raw_ids[0]), msg_key(raw_ids[2])}
n, abort = engine.retention.clear_filed(
    g, cfg4, confirmed, print, msg_key, lambda: __import__(
        "datetime").datetime(2026, 10, 22))
check("only confirmed items deleted", g.deleted == [raw_ids[0], raw_ids[2]],
      g.deleted)
check("count matches", n == 2 and abort is None, (n, abort))

g2 = FakeGraph([{"id": "raw-x", "receivedDateTime": "2026-10-01T00:00:00Z"}])
