PASS = FAIL = 0


def check(name, cond, detail=""):
    global PASS, FAIL
    if cond:
        PASS += 1
        print(f"  PASS  {name}")
    else:
        FAIL += 1
        print(f"  FAIL  {name}  {detail}")


def msg(sid, sender, subject, name=None, preview=""):
    addr, _, domain = sender.partition("@")
    return {"id": sid,
            "from": {"emailAddress": {"name": name or sender,
                                      "address": sender}},
            "subject": subject, "bodyPreview": preview, "isRead": False,
            "receivedDateTime": "2026-10-22T00:00:00Z"}


print("== 1. env config parses + version stable ==")
cfg = ECFG.from_env()
v1 = cfg.version
check("version is stable", cfg.version == v1)
check("env override honored", cfg.scan_top == 200, cfg.scan_top)
check("csv keywords parsed",
      "crossbar" in cfg.priority_keywords, cfg.priority_keywords)
check("default folders", cfg.filed_folder == "AIOS-Filed")

print("== 2. save -> load round-trip; file wins where it names a key ==")
# Real-flow shape: edits start from the CURRENT effective config (env),
# never from bare defaults — a saved snapshot therefore round-trips the
# env-raised knobs. (Once config.yaml exists it is authoritative; the file
# is regenerated by the same edit flow whenever env changes matter.)
edit_src = ECFG.asdict(cfg)
edit_src.update({"protected_domains": ["warnersstellian.com",
                                        "warners-stellian.com"],
                 "filed_days": 14})
saved = ECFG.save(ECFG.from_dict(edit_src, source="file"),
                  actor="test", state_dir=TMP)
cfg2 = ECFG.load(TMP)
check("file applied", cfg2.source == "file", cfg2.source)
check("file values win", cfg2.filed_days == 14
      and "warnersstellian.com" in cfg2.protected_domains)
check("merge: absent keys keep env values", cfg2.scan_top == 200, cfg2.scan_top)
check("version changed by the edit", cfg2.version == saved and
      saved != v1, (saved, v1))
# The legs that CONSUME config.yaml may run as a different uid than whatever
# wrote it, so the file must be world-readable — mkstemp's default 0600 was a
# silent file->env flip waiting to happen (caught live 2026-10-24).
mode = os.stat(ECFG.config_path(TMP)).st_mode & 0o777
check("config.yaml is world-readable (0644)", mode == 0o644, oct(mode))

print("== 3. journal is append-only + records actor ==")
hist = ECFG.history(TMP)
check("one journal row", len(hist) == 1 and hist[0]["actor"] == "test", hist)
ECFG.save(cfg2, actor="test2", state_dir=TMP)
check("appends, not rewrites", len(ECFG.history(TMP)) == 2)

