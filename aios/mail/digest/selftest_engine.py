#!/usr/bin/env python3
"""Offline self-test for the extracted engine (0.5.0): config store,
classifier fixtures, retention gate. Run BEFORE deploying.

    python3 selftest_engine.py
"""
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
PARENT = os.path.dirname(HERE)
TMP = tempfile.mkdtemp(prefix="aios-engine-test-")
os.environ["DIGEST_STATE_DIR"] = TMP
os.environ.setdefault("DIGEST_SCAN_TOP", "200")
os.environ.setdefault("DIGEST_PRIORITY_KEYWORDS",
                      "bluff creek,ccha,crossbar,bearpath")

for p in (PARENT,):  # make `import engine` work from anywhere
    if p not in sys.path:
        sys.path.insert(0, p)
import engine                        # noqa: E402
import engine.retention  # noqa: E402,F401 (explicit submodule import)
from engine import config as ECFG    # noqa: E402
from engine.classify import Classifier, msg_key  # noqa: E402

PASS = FAIL = 0


def check(name, cond, detail=""):
    global PASS, FAIL
    if cond:
        PASS += 1
        print(f"  PASS  {name}")
    else:
        FAIL += 1
        print(f"  FAIL  {name}  {detail}")


def msg(sid, sender, subject, name=None, preview=""):
    addr, _, domain = sender.partition("@")
    return {"id": sid,
            "from": {"emailAddress": {"name": name or sender,
                                      "address": sender}},
            "subject": subject, "bodyPreview": preview, "isRead": False,
            "receivedDateTime": "2026-10-22T00:00:00Z"}


print("== 1. env config parses + version stable ==")
cfg = ECFG.from_env()
v1 = cfg.version
check("version is stable", cfg.version == v1)
check("env override honored", cfg.scan_top == 200, cfg.scan_top)
check("csv keywords parsed",
      "crossbar" in cfg.priority_keywords, cfg.priority_keywords)
check("default folders", cfg.filed_folder == "AIOS-Filed")

print("== 2. save -> load round-trip; file wins where it names a key ==")
# Real-flow shape: edits start from the CURRENT effective config (env),
# never from bare defaults — a saved snapshot therefore round-trips the
# env-raised knobs. (Once config.yaml exists it is authoritative; the file
# is regenerated by the same edit flow whenever env changes matter.)
edit_src = ECFG.asdict(cfg)
edit_src.update({"protected_domains": ["warnersstellian.com",
                                        "warners-stellian.com"],
                 "filed_days": 14})
saved = ECFG.save(ECFG.from_dict(edit_src, source="file"),
                  actor="test", state_dir=TMP)
cfg2 = ECFG.load(TMP)
check("file applied", cfg2.source == "file", cfg2.source)
check("file values win", cfg2.filed_days == 14
      and "warnersstellian.com" in cfg2.protected_domains)
check("merge: absent keys keep env values", cfg2.scan_top == 200, cfg2.scan_top)
check("version changed by the edit", cfg2.version == saved and
      saved != v1, (saved, v1))

print("== 3. journal is append-only + records actor ==")
hist = ECFG.history(TMP)
check("one journal row", len(hist) == 1 and hist[0]["actor"] == "test", hist)
ECFG.save(cfg2, actor="test2", state_dir=TMP)
check("appends, not rewrites", len(ECFG.history(TMP)) == 2)

print("== 4. invalid config falls back to env (fail-safe, loud) ==")
bad = os.path.join(TMP, "broken-tmp")
os.makedirs(bad, exist_ok=True)
with open(os.path.join(bad, "config.yaml"), "w") as fh:
    fh.write("not_a_real_key: 3\nfiled_days: -5\n")
logs = []
cfg3 = ECFG.load(bad, log=logs.append)
check("fell back to env", cfg3.source == "env", cfg3.source)
check("warning was loud", any("unreadable" in s for s in logs), logs)
check("destructive value never applied", cfg3.filed_days == int(
    os.environ.get("DIGEST_FILED_DAYS", "10")))

print("== 3b. negative ints are refused by validate (regression: 0.5.x "
      "validate guard matched neither str nor type-object int) ==")
for neg in ({"filed_days": -3}, {"scan_top": -1}, {"digest_days": -2}):
    try:
        ECFG.from_dict(neg, source="file")
        check(f"refuse {neg}", False, "accepted destructive value")
    except ValueError:
        check(f"refuse {neg}(ValueError)", True)

print("== 5. classifier fixtures (0.4.x parity) ==")
base = ECFG.from_dict({
    "priority_keywords": ["bluff creek", "crossbar"],
    "protected_domains": ["warnersstellian.com"],
    "contact_excludes": ["ui.com"],
    "receipt_patterns": ["^receipt", "^invoice"],
    "order_patterns": ["order confirmation"],
    "privacy_domains": ["spokeo.com"],
    "notice_senders": ["notifications@github.com"],
    "notice_subjects": ["AIOS daily mail digest"],
}, source="file")
cl = Classifier(base)
contacts = {"principal@district.example"}

cases = [
    # (expected _file, expected self_notice/privacy/priority marker, fixture)
    (None, "notice", msg("m1", "notifications@github.com",
                         "Re: [ChadEngel/ce-aios] 📬 AIOS daily mail digest "
                         "(R0) — output thread")),
    (None, "notice", msg("m2", "Notifications@GitHub.com".lower(),
                         "aios DAILY mail digest")),
    ("filed", None, msg("m3", "xnotifications@github.com",
                        "AIOS daily mail digest")),
    ("filed", None, msg("m4", "notifications@github.com.evil.com",
                        "AIOS daily mail digest")),
    ("filed", None, msg("m5", "attacker@evil.com",
                        "Re: AIOS daily mail digest (R0)")),
    ("filed", None, msg("m6", "noreply@github.com", "AIOS daily mail digest")),
    (None, "priority", msg("m7", "coach@ccunited.example",
                           "Crossbar schedules for Saturday", name="CC United")),
    (None, "priority", msg("m8", "sales@warnersstellian.com",
                           "your order is ready")),
    ("receipts", None, msg("m9", "billing@store.example",
                           "Receipt from The Store")),
    ("orders", None, msg("m10", "ship@shop.example",
                         "Your order confirmation")),
    (None, "privacy", msg("m11", "auto@spokeo.com",
                          "who's searching for you?")),
]
out = cl.classify([c[2] for c in cases], contacts)
byid = {c["_id"]: c for c in out}
for expected_file, marker, fixture in cases:
    c = byid[msg_key(fixture["id"])]
    if marker == "notice":
        check(f"{fixture['id']} kept as notice", bool(c["_self_notice"]))
    elif marker == "priority":
        ok = c["type"] == "priority" and c["_file"] is None
        check(f"{fixture['id']} priority", ok, c)
    elif marker == "privacy":
        check(f"{fixture['id']} privacy-kept",
              bool(c["_privacy"]) and c["_file"] is None, c)
    else:
        check(f"{fixture['id']} -> {expected_file}", c["_file"] == expected_file,
              (c["_file"], c["reason"]))

# sent-contacts tier + excludes
m_ex = cl.classify([msg("m12", "news@ui.com", "your account update"),
                    msg("m13", "friend@example.com", "hi")],
                   contacts | {"news@ui.com", "friend@example.com"})
m12 = next(c for c in m_ex if c["_id"] == msg_key("m12"))
m13 = next(c for c in m_ex if c["_id"] == msg_key("m13"))
check("excluded contact falls through to junk", m12["_file"] == "filed",
      (m12["_file"], m12["reason"]))
check("emailed friend stays priority", m13["type"] == "priority"
      and m13["_file"] is None, m13)

print("== 6. schedule validation + next-fire maths (R1) ==")
from engine import schedule as SCHED  # noqa: E402

# default pair from env/config must be valid (behaviour-neutral introduction)
check("default schedule valid",
      SCHED.validate_schedule(cfg.digest_schedule, cfg.digest_tz) is True)
check("3x/day default -> next fire exists",
      len(SCHED.next_fires("0 5,12,17 * * *", "America/Chicago", 3)) == 3)

# invalid cron expression refused
for bad in ("", "not a cron", "0 5,12,17 * *", "99 * * * *"):
    try:
        SCHED.validate_schedule(bad, "America/Chicago")
        check(f"refuse cron {bad!r}", False, "accepted")
    except ValueError:
        check(f"refuse cron {bad!r}", True)

# unknown timezone refused
try:
    SCHED.validate_schedule("0 5 * * *", "Mars/Olympus_Mons")
    check("refuse bad tz", False, "accepted")
except ValueError:
    check("refuse bad tz", True)

# 1-fire/hour floor: an hourly hammer is refused (mis-typed expression guard)
try:
    SCHED.validate_schedule("*/5 * * * *", "America/Chicago")
    check("refuse >1/hour schedule", False, "accepted */5")
except ValueError:
    check("refuse >1/hour schedule", True)
# exactly 1/hour is ALLOWED (the floor is a floor, not a ban on hourly)
check("hourly is allowed (gap == 3600s)",
      SCHED.validate_schedule("0 * * * *", "America/Chicago") is True)

# config.validate() must refuse a bad schedule end-to-end (save-time gate)
for bad in ({"digest_schedule": "nope"}, {"digest_tz": "Nowhere/Land"},
            {"digest_schedule": "*/5 * * * *"}):
    try:
        ECFG.from_dict(bad, source="file")
        check(f"config refuses {bad}", False, "accepted")
    except ValueError:
        check(f"config refuses {bad}", True)

# DST: a 5am local fire stays 5am local across the fall-back shift. Anchor
# before/after the 2026-11-01 US fall-back; the local hour must be 5 both times.
from datetime import datetime, timezone  # noqa: E402
dst_fires = SCHED._next_anchored("0 5 * * *", "America/Chicago", 300,
                                 now=datetime(2026, 10, 25, 12, tzinfo=timezone.utc))
local_hours = {d.hour for d in dst_fires}
check("DST: 5am stays 5am across fall-back", local_hours == {5}, sorted(local_hours))

# describe() never raises and reports validity + advisories
d = SCHED.describe("0 5,12,17 * * *", "America/Chicago")
check("describe valid", d["valid"] and len(d["next"]) == 5, d)
d2 = SCHED.describe("garbage", "America/Chicago")
check("describe invalid is graceful", d2["valid"] is False and d2["next"] == [], d2)
d3 = SCHED.describe("0 5 * * *", "America/Chicago")  # minute 0 == filer heartbeat
check("filer minute advisory is advisory-only (still valid)",
      d3["valid"] and d3["advisories"], d3)

print("== 7. retention gate (F5) with a fake graph ==")


class FakeGraph:
    def __init__(self, items):
        self.items = list(items)   # [{"id": raw-graph-id}]
        self.deleted = []

    def list_folders(self):
        return {"aios-filed": "F1"}

    def list_folder(self, fid, top, skip=None, filter=None, orderby=None):
        return [m for m in self.items]

    def delete(self, mid):
        self.deleted.append(mid)
        self.items[:] = [m for m in self.items if m["id"] != mid]
        return None


raw_ids = [f"raw-{i}" for i in range(4)]
g = FakeGraph([{"id": rid, "receivedDateTime": "2026-10-01T00:00:00Z"}
               for rid in raw_ids])
cfg4 = ECFG.from_dict({"filed_days": 10, "filed_folder": "AIOS-Filed"})
confirmed = {msg_key(raw_ids[0]), msg_key(raw_ids[2])}
n, abort = engine.retention.clear_filed(
    g, cfg4, confirmed, print, msg_key, lambda: __import__(
        "datetime").datetime(2026, 10, 22))
check("only confirmed items deleted", g.deleted == [raw_ids[0], raw_ids[2]],
      g.deleted)
check("count matches", n == 2 and abort is None, (n, abort))

g2 = FakeGraph([{"id": "raw-x", "receivedDateTime": "2026-10-01T00:00:00Z"}])
n2, _ = engine.retention.clear_filed(g2, cfg4, None, print, msg_key,
                                     lambda: __import__(
                                         "datetime").datetime(2026, 10, 22))
check("gate-off falls back to age-only (compat)", n2 == 1 and
      g2.deleted == ["raw-x"])

g3 = FakeGraph([{"id": "r"}])
cfg5 = ECFG.from_dict({"filed_days": 0, "filed_folder": "AIOS-Filed"})
n3, _ = engine.retention.clear_filed(g3, cfg5, None, print, msg_key,
                                     lambda: __import__(
                                         "datetime").datetime(2026, 10, 22))
check("filed_days=0 = keep forever (D3 destructive-config refusal)", n3 == 0)

print(f"\n{PASS} passed, {FAIL} failed")
sys.exit(1 if FAIL else 0)